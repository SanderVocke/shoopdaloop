result.exports = await exportBindings(wasm, BrowserClient, BrowserBridge, BrowserExportClient);
result.checks.push("immutable exports across both revisions and all 16 initial MIDI channels");
result.staging=await stagingBindings(wasm,BrowserClient,BrowserBridge,BrowserStagingClient);
result.checks.push("owning resource uploads and prepared nested-program staging");
result.dense=await denseBindings(wasm,BrowserClient,BrowserBridge);
result.checks.push("dense wraps, cascades and clocked composites with unread results");
result.stalls=await denseBindings(wasm,BrowserClient,BrowserBridge,true);
result.checks.push("acknowledged restart with unpolled result transport");
result.media=await mediaBindings(wasm,BrowserClient,BrowserBridge,BrowserStagingClient,BrowserExportClient);
result.checks.push("playable replacement, tick-delayed capture and coherent exhausted prefix export");
result.planner=plannerBindings(wasm,BrowserPlannerCanary);
result.checks.push("real resolver planner lifecycle control and distinct planner error/heap origins");
console.log(JSON.stringify({ ...result, node: process.version }));
