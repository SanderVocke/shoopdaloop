#!/usr/bin/env python3
"""Connect semantic audio and private loader ownership to the real media store."""
import argparse
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "axi_memory"))
from generate_tops import header
from generate_semantic import generate as audio


def connections(text):
    result = {}
    for match in re.finditer(r"\.(\w+)\(", text):
        start = match.end()
        depth, end = 1, start
        while depth:
            depth += (text[end] == "(") - (text[end] == ")")
            end += 1
        result[match[1]] = text[start:end-1].strip()
    return result


def instance(text, kind, name):
    match = re.search(rf"{kind} #\((.*?)\) {name} \((.*?)\n    \);", text, re.S)
    assert match, (kind, name)
    return connections(match[1]), connections(match[2])


def emit(kind, name, params, ports):
    return f"    {kind} #(\n" + ",\n".join(f"        .{n}({v})" for n, v in params.items()) + f"\n    ) {name} (\n" + ",\n".join(f"        .{n}({v})" for n, v in ports.items()) + "\n    );\n"


def generate():
    legacy = (HERE.parent / "media_store/rtl/media_audio_pipeline.sv").read_text()
    media, old_public = header(legacy)
    _, old_core = header((HERE.parent / "job_processor/rtl/audio_pipeline.sv").read_text())
    core, core_ports = header(audio())
    _, arbiter = header((HERE / "rtl/fifo_media_arbiter.sv").read_text())
    obsolete = {n for _, n in old_core} - {n for _, n in core_ports}
    public = [(p, n) for p, n in old_public if n not in obsolete]
    private_core = {n for _, n in core_ports if n.startswith("media_")}
    private_core.update({"capture_credits", "handoff_request", "handoff_valid", "handoff_error", "handoff_epoch", "handoff_sequence"})
    public.extend((p, n) for p, n in core_ports if n not in private_core and n not in {n for _, n in public})
    public.extend([("input wire ", "store_response_ready"), ("output wire [31:0] ", "store_result_count")])
    params = re.sub(r"\s*parameter integer (?:LIVE_LOADING|EXPORT_SYNC_EVENTS|PROGRAM_REGIONS) = [^,]+,", "", media[2]).strip()
    params += ",\n    parameter integer LOOP_DEPTH = 128"
    for n, value in {"PROGRAM_DEPTH": 1024, "STATE_DEPTH": 512, "JOB_DEPTH": 1024, "BUFFERS": 512, "INPUT_PORTS": 1}.items():
        params = re.sub(rf"(parameter integer {n} = )[^,\n]+", rf"\g<1>{value}", params)
    text = '// Generated by generate_semantic_media.py; do not edit by hand.\n`include "state_processor_defs.svh"\n\n'
    text += f"module fifo_media_audio_pipeline #(\n    {params}\n) (\n"
    text += ",\n".join("    " + p.replace("output reg", "output wire") + n for p, n in public) + "\n);\n"
    common = legacy[legacy.index("    wire pipeline_busy"):legacy.index("    assign busy")].replace("    reg completion_pending;\n", "")
    text += common
    text += "    wire [31:0] pipeline_diagnostic_cause;\n"
    text += "    assign diagnostic_cause = pipeline_diagnostic_cause | (memory_fault ? 32'd1 : 0);\n"
    declared = {n for _, n in public} | set(re.findall(r"\b([a-z_]\w*)\s*[,;]", common))
    links = {"processing_due": "run_valid", "frontend_busy": "pipeline_busy", "faulted": "media_control_fault", "fence_request": "handoff_request",
             "fence_response_valid": "handoff_valid", "fence_response_error": "handoff_error", "fence_response_epoch": "handoff_epoch", "fence_response_sequence": "handoff_sequence",
             "loader_response_valid": "store_done", "loader_response_ready": "store_response_ready", "loader_response_error": "store_error_code",
             "operation_ready": "internal_ready", "operation_done": "internal_done", "operation_error": "internal_error",
             "operation_write_ready": "internal_write_ready", "operation_read_valid": "internal_read_valid", "operation_read_data": "store_sample",
             "operation_result_view": "internal_result_view", "operation_result_empty": "internal_result_empty"}
    for _, n in arbiter:
        if n.startswith("loader_") and n not in links:
            links[n] = n.replace("loader_", "store_", 1)
    for p, n in arbiter:
        name = links.get(n, n)
        if name not in declared:
            text += "    " + re.sub(r"(?:input|output)\s+(?:wire|reg)", "wire", p) + name + ";\n"
            declared.add(name)
    text += "    assign busy = pipeline_busy;\n    assign done = pipeline_done;\n    assign run_ready = pipeline_ready;\n"
    text += "    assign cfg_ready = state_cfg_ready && !run_valid;\n    assign audio_cfg_ready = sample_cfg_ready && !pipeline_busy && !run_valid;\n"
    text += "    assign store_cfg_ready = internal_cfg_ready && !pipeline_busy && !run_valid;\n"
    pipe_params, pipe = instance(legacy, "audio_pipeline", "pipeline")
    pipe.update({"run_valid": "run_valid", "cfg_valid": "cfg_valid && !run_valid", "audio_cfg_valid": "audio_cfg_valid && !pipeline_busy && !run_valid",
                 "media_done": "job_done", "media_error": "job_error", "media_fault": "memory_fault || media_control_fault", "media_read_data": "job_read_data",
                 "pipeline_fault": "pipeline_fault || media_control_fault || memory_fault", "sync_event_valid": "sync_event_valid", "sync_event_data": "sync_event_data",
                 "capture_valid": "capture_valid", "capture_frame": "capture_frame",
                 "diagnostic_cause": "pipeline_diagnostic_cause"})
    names = set(re.findall(r"parameter integer (\w+)\s*=", core[2]))
    pipe_params = {n: v for n, v in pipe_params.items() if n in names}
    pipe_params["LOOP_DEPTH"] = "LOOP_DEPTH"
    text += emit("fifo_audio_pipeline", "pipeline", pipe_params, {n: pipe.get(n, n) for _, n in core_ports})
    text += emit("fifo_media_arbiter", "owner", {"MAX_WORDS": "CHUNK_FRAMES"}, {n: links.get(n, n) for _, n in arbiter})
    store_params, store = instance(legacy, "media_store", "media")
    store.update({"cmd_valid": "operation_valid", "cmd_ready": "internal_ready", "cmd_opcode": "operation_opcode", "cmd_view": "operation_view",
                  "cmd_start": "operation_start", "cmd_length": "operation_length", "cmd_count": "operation_count", "error_code": "internal_error",
                  "result_view": "internal_result_view", "result_empty": "internal_result_empty", "write_valid": "operation_write_valid", "write_data": "operation_write_data",
                  "read_ready": "operation_read_ready", "cfg_valid": "store_cfg_valid && !pipeline_busy && !run_valid"})
    text += emit("media_store", "media", store_params, store)
    delay_params, delay = instance(legacy, "memory_delay", "delay")
    return text + emit("memory_delay", "delay", delay_params, delay) + "endmodule\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = HERE / "rtl/fifo_media_audio_pipeline.sv"
    text = generate()
    if args.check:
        if not path.is_file() or path.read_text() != text:
            raise SystemExit(f"stale generated top: {path}; run {__file__}")
    else:
        path.write_text(text)


if __name__ == "__main__":
    main()
