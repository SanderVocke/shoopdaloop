#!/usr/bin/env python3
"""Generate the shared host mailbox register definitions."""

import argparse
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def generate(check):
    spec = json.loads((HERE / "registers.json").read_text())
    registers = {name: int(value, 16) for name, value in spec["registers"].items()}
    bits = spec["status_bits"]
    words = spec["payload_words"]
    occupied = [offset + 4 * word for name, offset in registers.items()
                for word in range(words if name.endswith("_DATA") else 1)]
    if len(occupied) != len(set(occupied)) or any(offset % 4 or not 0 <= offset < 4096 for offset in occupied):
        raise ValueError("Overlapping, unaligned or out-of-range register")
    if len(bits) != len(set(bits.values())) or any(not 0 <= bit < 32 for bit in bits.values()):
        raise ValueError("Overlapping or out-of-range status bits")

    identity = int(spec["id"], 16)
    version = spec["version"]
    sv = [f"localparam logic [31:0] HOST_ID = 32'h{identity:08x};",
          f"localparam logic [31:0] HOST_VERSION = 32'd{version};",
          f"localparam integer HOST_PAYLOAD_WORDS = {words};"]
    sv += [f"localparam logic [11:0] REG_{name} = 12'h{offset:03x};" for name, offset in registers.items()]
    sv += [f"localparam integer STATUS_{name} = {bit};" for name, bit in bits.items()]

    rust = ["// Generated by generate_registers.py.",
            f"pub const HOST_ID: u32 = 0x{identity:08x};",
            f"pub const HOST_VERSION: u32 = {version};",
            f"pub const HOST_PAYLOAD_WORDS: usize = {words};"]
    rust += [f"pub const REG_{name}: u32 = 0x{offset:03x};" for name, offset in registers.items()]
    rust += [f"pub const STATUS_{name}: u32 = 1 << {bit};" for name, bit in bits.items()]
    fault_bits = spec["fault_bits"]
    if len(fault_bits) != len(set(fault_bits.values())) or any(not 0 <= bit < 32 for bit in fault_bits.values()):
        raise ValueError("Overlapping or out-of-range fault bits")
    sv += [f"localparam logic [31:0] FAULT_{name} = 32'h{1 << bit:08x};" for name, bit in fault_bits.items()]
    rust += [f"pub const FAULT_{name}: u32 = 1 << {bit};" for name, bit in fault_bits.items()]
    for key, prefix in [("operations", "OP"), ("response_codes", "RESULT"), ("submission_codes", "SUBMIT")]:
        values = spec[key]
        if len(values) != len(set(values.values())) or any(not 0 <= value <= 0xff for value in values.values()):
            raise ValueError(f"Overlapping or out-of-range {key}")
        sv += [f"localparam logic [31:0] {prefix}_{name} = 32'd{value};" for name, value in values.items()]
        rust += [f"pub const {prefix}_{name}: u32 = {value};" for name, value in values.items()]
    sv = ["// Generated by generate_registers.py.", "package host_registers;",
          *("    " + line for line in sv), "endpackage"]

    for path, lines in [(HERE / "rtl/host_registers.sv", sv),
                        (ROOT / "src/rust/rt_fpga_rtl/src/host/registers.rs", rust),
                        *native_audio_definitions()]:
        contents = "\n".join(lines) + "\n"
        if check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"Stale register definitions in {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)


def native_audio_definitions():
    spec = json.loads((HERE / "native_audio.json").read_text())
    registers = {name: int(value, 16) for name, value in spec["registers"].items()}
    quantum = spec["quantum"]
    occupied = [offset + 4 * word for name, offset in registers.items()
                for word in range({"RX_BASE": quantum, "TX_BASE": 2 * quantum}.get(name, 1))]
    bits = spec["status_bits"]
    if len(occupied) != len(set(occupied)) or any(offset % 4 or not 0 <= offset < 4096 for offset in occupied):
        raise ValueError("Overlapping, unaligned or out-of-range native audio register")
    if len(bits) != len(set(bits.values())) or any(not 0 <= bit < 32 for bit in bits.values()):
        raise ValueError("Overlapping or out-of-range native audio status bits")

    constants = [("ID", int(spec["id"], 16)), ("VERSION", spec["version"]),
                 ("QUANTUM", quantum), ("SAMPLE_RATE", spec["sample_rate"])]
    sv = ["// Generated by generate_registers.py.", "package native_audio_registers;"]
    sv += [f"    localparam logic [31:0] AUDIO_{name} = 32'h{value:08x};" for name, value in constants]
    sv += [f"    localparam logic [11:0] REG_{name} = 12'h{offset:03x};" for name, offset in registers.items()]
    sv += [f"    localparam integer STATUS_{name} = {bit};" for name, bit in bits.items()]
    sv.append("endpackage")
    header = ["/* Generated by generate_registers.py. */", "#pragma once"]
    header += [f"#define SHOOP_AUDIO_{name} 0x{value:x}u" for name, value in constants]
    header += [f"#define SHOOP_AUDIO_REG_{name} 0x{offset:03x}u" for name, offset in registers.items()]
    header += [f"#define SHOOP_AUDIO_STATUS_{name} (1u << {bit})" for name, bit in bits.items()]
    return [(HERE / "rtl/native_audio_registers.sv", sv),
            (ROOT / "platforms/zynq7000/include/native_audio_registers.h", header)]


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
