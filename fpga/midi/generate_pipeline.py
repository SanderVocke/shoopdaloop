#!/usr/bin/env python3
"""Generate the shared-SP/JP MIDI pipeline boundary from public core ports."""
import argparse
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'axi_memory'))
from generate_tops import header

MIDI_PARAMS = dict(STATE_SUPPORTED=0, LOOPS=128, INPUTS=1, DESTINATIONS=8, BUFFERS=256,
                   CURSORS=128, SCRATCH_EVENTS=131072, BLOCK_EVENTS=256,
                   BLOCKS=4864, MAX_EVENTS=8192, VIEWS=512,
                   RETIREMENTS=256, MAINTENANCE=64, RECORD_BURSTS=0)

def generate():
    audio, audio_ports = header((HERE.parent / 'axi_memory/rtl/media_audio_pipeline_axi.sv').read_text())
    service, service_ports = header((HERE / 'rtl/midi_data_jobs.sv').read_text())
    audio_params = [p.strip() for p in audio[2].split(',') if not re.search(r'\bENABLE_MIDI\b', p)]
    audio_names = [re.search(r'(\w+)\s*=', p)[1] for p in audio_params]
    ports = [(p, n) for p, n in audio_ports if not n.startswith('midi_job_')]
    ports += [('output wire ', 'midi_publication_valid'), ('input wire ', 'midi_publication_commit'),
              ('input wire [63:0] ', 'midi_arena_base'), ('output wire [63:0] ', 'midi_arena_bytes'),
              ('input wire [63:0] ', 'midi_event_address'), ('input wire [31:0] ', 'midi_event_count')]
    private = {'clk','reset','arena_base','arena_bytes','quantum_frames','idle','control_enable','fault_request',
               'publication_valid','publication_commit','event_address','event_count'}
    private.update(n for _,n in service_ports if n.startswith(('job_','prepare_','finish_')))
    ports += [(p.replace('output reg','output wire'),'midi_'+n) for p,n in service_ports if n not in private]
    params = audio_params + [f'parameter integer MIDI_{k} = {v}' for k, v in MIDI_PARAMS.items()]
    lines = ['// Generated by fpga/midi/generate_pipeline.py.', '`include "state_processor_defs.svh"',
             'module midi_audio_pipeline #(', ',\n'.join('    '+p for p in params), ') (',
             ',\n'.join('    '+p+n for p,n in ports), ');',
             '    localparam [2:0] IDLE=0, PREPARE=1, START=2, RUN=3, FINISH=4;',
             '    reg [2:0] phase;',
             '    reg completed, finish_accepted, engine_fault;',
             '    reg [7:0] result_error;', '    reg [1:0] result_stage;', '    reg [3:0] result_midi_error;',
             '    wire audio_run_ready, audio_busy, audio_done, midi_idle;',
             '    wire [7:0] audio_error;', '    wire [1:0] audio_stage;', '    wire [3:0] audio_midi_error;',
             '    wire prepare_ready, prepare_done, finish_ready, finish_done;',
             '    wire [3:0] prepare_error, finish_error;',
             '    wire accepted=run_valid && run_ready;',
             '    wire midi_job_valid,midi_job_ready,midi_job_done;',
             '    wire [255:0] midi_job_data;', '    wire [3:0] midi_job_error;']
    run_ports=[(p,n) for p,n in audio_ports if n.startswith('run_') and n not in {'run_valid','run_ready'}]
    for prefix,name in run_ports:
        lines.append('    '+re.sub(r'input\s+wire','reg',prefix)+'saved_'+name+';')
    gated=['cfg','audio_cfg','switch','store_cmd','store_cfg']
    for prefix in gated:
        if any(n==prefix+'_ready' for _,n in audio_ports): lines.append(f'    wire gated_{prefix}_ready;')
    lines += [
        '    assign run_ready=phase==IDLE && audio_run_ready && midi_idle && prepare_ready && !engine_fault;',
        '    assign busy=phase!=IDLE || audio_busy;', '    assign done=completed;',
        '    assign error_code=result_error;', '    assign error_stage=result_stage;', '    assign midi_error_code=result_midi_error;',
        '    always @(posedge clk) begin',
        '        if(reset) begin phase<=IDLE;completed<=0;finish_accepted<=0;engine_fault<=0;result_error<=0;result_stage<=0;result_midi_error<=0;end',
        '        else begin', '            completed<=0;', '            case(phase)',
        '                IDLE: if(accepted) begin phase<=PREPARE;finish_accepted<=0;result_error<=0;result_stage<=0;result_midi_error<=0;end',
        '                PREPARE: if(prepare_done) begin',
        "                    if(prepare_error!=0) begin result_error<=4;result_stage<=2;result_midi_error<=prepare_error;if(prepare_error==7) engine_fault<=1;completed<=1;phase<=IDLE;end",
        '                    else phase<=START;', '                end',
        '                START: if(audio_run_ready) phase<=RUN;',
        '                RUN: if(audio_done) begin',
        '                    result_error<=audio_error;result_stage<=audio_stage;result_midi_error<=audio_midi_error;',
        '                    if(audio_error!=0) begin engine_fault<=1;completed<=1;phase<=IDLE;end else phase<=FINISH;', '                end',
        '                FINISH: begin', '                    if(finish_ready) finish_accepted<=1;',
        '                    if(finish_done) begin',
        '                        if(finish_error!=0) begin engine_fault<=1;result_error<=4;result_stage<=2;result_midi_error<=finish_error;end',
        '                        completed<=1;phase<=IDLE;', '                    end', '                end',
        '                default: phase<=IDLE;', '            endcase', '        end', '    end',
        '    always @(posedge clk) if(accepted) begin']
    lines += [f'        saved_{name}<={name};' for _,name in run_ports]
    lines += ['    end']
    overrides=dict(run_valid='phase==START',run_ready='audio_run_ready',busy='audio_busy',done='audio_done',
                   error_code='audio_error',error_stage='audio_stage',midi_error_code='audio_midi_error')
    overrides.update((name,'saved_'+name) for _,name in run_ports)
    for prefix in gated:
        if any(n==prefix+'_ready' for _,n in audio_ports):
            lines.append(f'    assign {prefix}_ready=gated_{prefix}_ready && phase==IDLE;')
            overrides[prefix+'_ready']='gated_'+prefix+'_ready'
            overrides[prefix+'_valid']=prefix+'_valid && phase==IDLE'
    lines += ['    media_audio_pipeline_axi #(', ',\n'.join(f'        .{n}({n})' for n in audio_names)+',\n        .ENABLE_MIDI(1)', '    ) audio (',
              ',\n'.join(f'        .{n}({overrides.get(n,n)})' for _,n in audio_ports), '    );',
              '    midi_data_jobs #(', ',\n'.join(f'        .{n}(MIDI_{n})' for n in MIDI_PARAMS), '    ) midi (']
    internal=dict(clk='clk',reset='reset',arena_base='midi_arena_base',arena_bytes='midi_arena_bytes',
                  quantum_frames='phase==IDLE ? run_quantum : saved_run_quantum',
                  idle='midi_idle',control_enable='phase==IDLE && !run_valid',fault_request='audio_error!=0',
                  publication_valid='midi_publication_valid',publication_commit='midi_publication_commit',
                  event_address='midi_event_address',event_count='midi_event_count',
                  prepare_valid='accepted',finish_valid='phase==FINISH && !finish_accepted')
    internal.update((n,n) for _,n in service_ports if n.startswith(('prepare_','finish_')) and n not in internal)
    internal.update((n,'midi_'+n) for _,n in service_ports if n.startswith('job_'))
    lines += [',\n'.join(f'        .{n}({internal.get(n,"midi_"+n)})' for _,n in service_ports),'    );','endmodule']
    return '\n'.join(lines)+'\n'

def generate_axi(core):
    match, ports = header(core)
    params = match[2].strip().replace('MIDI_RECORD_BURSTS = 0', 'MIDI_RECORD_BURSTS = 1')
    names = re.findall(r"parameter\s+(?:integer|\[[^]]+\])\s+(\w+)\s*=", params)
    _, word_ports = header((HERE.parent/'axi_memory/rtl/word_axi.sv').read_text())
    public = [(p,n) for p,n in ports if not n.startswith('midi_memory_')]
    private = [(p,n) for p,n in ports if n.startswith('midi_memory_')]
    axi = [(p.replace('DATA_WIDTH','MIDI_AXI_DATA_WIDTH'),'midi_'+n) for p,n in word_ports if n.startswith('m_axi_')]
    public += [('input wire [63:0] ','midi_memory_arena_bytes')]
    params += ",\n    parameter integer MIDI_AXI_DATA_WIDTH = 64,\n    parameter [31:0] MIDI_PHYSICAL_BASE = 32'h30000000,\n    parameter [63:0] MIDI_PHYSICAL_BYTES_LIMIT = 64'd67108864"
    text = '// Generated by fpga/midi/generate_pipeline.py.\n`include "state_processor_defs.svh"\n'
    text += 'module midi_audio_pipeline_axi #(\n'+params+'\n) (\n'
    text += ',\n'.join('    '+p+n for p,n in public+axi)+'\n);\n'
    for prefix,n in private:
        text += '    '+re.sub(r'(input|output)\s+(wire|reg)', 'wire', prefix)+n+';\n'
    text += '    midi_audio_pipeline #(\n'+',\n'.join(f'        .{n}({n})' for n in names)+'\n    ) core (.*);\n'
    text += "    wire [63:0] checked_bytes = midi_memory_arena_bytes<=MIDI_PHYSICAL_BYTES_LIMIT ? midi_memory_arena_bytes : 0;\n"
    text += '    word_axi #(.DATA_WIDTH(MIDI_AXI_DATA_WIDTH),.REGISTER_REQUEST(1),.RECORD_BURSTS(MIDI_RECORD_BURSTS)) midi_memory (\n'
    fixed = dict(clk='clk',reset='reset',arena_base='midi_arena_base',arena_bytes='checked_bytes',physical_base='MIDI_PHYSICAL_BASE')
    mappings = []
    for _,n in word_ports:
        mappings.append(f'        .{n}({fixed.get(n,"midi_"+n)})')
    text += ',\n'.join(mappings)+'\n    );\nendmodule\n'
    return text

def generate_data_axi():
    core, ports = header((HERE/'rtl/midi_data_jobs.sv').read_text())
    _, word_ports = header((HERE.parent/'axi_memory/rtl/word_axi.sv').read_text())
    names=re.findall(r'\b(\w+)\s*=',core[2])
    public=[(p.replace('output reg','output wire'),n) for p,n in ports if not n.startswith('memory_')]
    public += [('input wire [63:0] ','memory_arena_bytes'),('input wire [31:0] ','physical_base')]
    public += [(p,n) for p,n in word_ports if n.startswith('m_axi_')]
    text='// Generated by fpga/midi/generate_pipeline.py.\nmodule midi_data_jobs_axi #(\n'+core[2].replace('RECORD_BURSTS=0', 'RECORD_BURSTS=1')+',\n    parameter integer DATA_WIDTH=64\n) (\n'
    text+=',\n'.join('    '+p+n for p,n in public)+'\n);\n'
    for prefix,n in ports:
        if n.startswith('memory_'): text+='    '+re.sub(r'(input|output)\s+(wire|reg)','wire',prefix)+n+';\n'
    text+='    midi_data_jobs #(\n'+',\n'.join(f'        .{n}({n})' for n in names)+'\n    ) core (.*);\n'
    text+='    word_axi #(.DATA_WIDTH(DATA_WIDTH),.REGISTER_REQUEST(1),.RECORD_BURSTS(RECORD_BURSTS)) memory (\n'
    mappings=dict(arena_bytes='memory_arena_bytes')
    text+=',\n'.join(f'        .{n}({mappings.get(n,n)})' for _,n in word_ports)+'\n    );\nendmodule\n'
    return text

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    core = generate()
    for name, text in [('midi_audio_pipeline',core),('midi_audio_pipeline_axi',generate_axi(core)),('midi_data_jobs_axi',generate_data_axi())]:
        path = HERE/'rtl'/f'{name}.sv'
        if args.check:
            if path.read_text() != text: raise SystemExit(f'Stale generated {name}')
        else:
            path.write_text(text)
