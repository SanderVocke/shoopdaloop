#!/usr/bin/env python3
"""Generate the shared-SP/JP MIDI pipeline boundary from public core ports."""
import argparse
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'axi_memory'))
from generate_tops import header

MIDI_PARAMS = dict(LOOPS=128, INPUTS=1, DESTINATIONS=8, BLOCK_EVENTS=256,
                   BLOCKS=4864, MAX_EVENTS=8192, VIEWS=512,
                   RETIREMENTS=256, INPUT_EVENTS=256, MAINTENANCE=64)

def generate():
    audio, audio_ports = header((HERE.parent / 'axi_memory/rtl/media_audio_pipeline_axi.sv').read_text())
    service, service_ports = header((HERE / 'rtl/midi_job_service.sv').read_text())
    audio_params = [p.strip() for p in audio[2].split(',') if not re.search(r'\bENABLE_MIDI\b', p)]
    audio_names = [re.search(r'(\w+)\s*=', p)[1] for p in audio_params]
    ports = [(p, n) for p, n in audio_ports if not n.startswith('midi_job_')]
    ports += [('output wire ', 'midi_publication_valid'), ('input wire ', 'midi_publication_commit'),
              ('input wire [63:0] ', 'midi_arena_base'), ('output wire [63:0] ', 'midi_arena_bytes'),
              ('input wire [63:0] ', 'midi_event_address'), ('input wire [31:0] ', 'midi_event_count')]
    excluded = {'clk', 'reset', 'arena_base', 'arena_bytes', 'quantum_frames'}
    for prefix, name in service_ports:
        if name not in excluded:
            ports.append((prefix.replace('output reg', 'output wire'), 'midi_' + name))
    params = audio_params + [f'parameter integer MIDI_{k} = {v}' for k, v in MIDI_PARAMS.items()]
    lines = ['// Generated by fpga/midi/generate_pipeline.py.', '`include "state_processor_defs.svh"',
             'module midi_audio_pipeline #(', ',\n'.join('    ' + p for p in params), ') (',
             ',\n'.join('    ' + p + n for p, n in ports), ');',
             '    wire midi_job_valid, midi_job_ready, midi_job_done;',
             '    wire [255:0] midi_job_data;', '    wire [3:0] midi_job_error;',
             '    wire audio_run_ready, midi_idle;',
             '    wire audio_run_valid = run_valid && midi_idle && !midi_command_valid;',
             '    assign run_ready = audio_run_ready && midi_idle && !midi_command_valid;',
             '    reg [63:0] event_address;', '    reg [31:0] event_count, midi_quantum;',
             '    always @(posedge clk) begin',
             "        if(reset) begin event_address<=0;event_count<=0;midi_quantum<=32'(MAX_FRAMES);end",
             '        else if(run_valid && run_ready) begin',
             '            event_address<=midi_event_address;event_count<=midi_event_count;midi_quantum<=run_quantum;',
             '        end', '    end',
             '    media_audio_pipeline_axi #(',
             ',\n'.join(f'        .{n}({n})' for n in audio_names) + ',\n        .ENABLE_MIDI(1)', '    ) audio (']
    overrides = dict(run_valid='audio_run_valid', run_ready='audio_run_ready')
    lines += [',\n'.join(f'        .{n}({overrides.get(n,n)})' for _, n in audio_ports), '    );',
              '    midi_job_port #(', ',\n'.join(f'        .{n}(MIDI_{n})' for n in MIDI_PARAMS),
              '    ) midi (', '        .idle(midi_idle), .control_enable(!busy), .fault_request(error_code!=0),',
              '        .publication_valid(midi_publication_valid), .publication_commit(midi_publication_commit),',
              '        .job_valid(midi_job_valid), .job_ready(midi_job_ready), .job_data(midi_job_data),',
              '        .job_done(midi_job_done), .job_error(midi_job_error),',
              '        .event_address(event_address), .event_count(event_count),']
    service_overrides = dict(clk='clk', reset='reset', arena_base='midi_arena_base', arena_bytes='midi_arena_bytes', quantum_frames='midi_quantum')
    lines += [',\n'.join(f'        .{n}({service_overrides.get(n,"midi_"+n)})' for _, n in service_ports), '    );', 'endmodule']
    return '\n'.join(lines) + '\n'

def generate_axi(core):
    match, ports = header(core)
    params = match[2].strip()
    names = re.findall(r"parameter\s+(?:integer|\[[^]]+\])\s+(\w+)\s*=", params)
    _, word_ports = header((HERE.parent/'axi_memory/rtl/word_axi.sv').read_text())
    public = [(p,n) for p,n in ports if not n.startswith('midi_memory_')]
    private = [(p,n) for p,n in ports if n.startswith('midi_memory_')]
    axi = [(p.replace('DATA_WIDTH','MIDI_AXI_DATA_WIDTH'),'midi_'+n) for p,n in word_ports if n.startswith('m_axi_')]
    public += [('input wire [63:0] ','midi_memory_arena_bytes')]
    params += ",\n    parameter integer MIDI_AXI_DATA_WIDTH = 64,\n    parameter [31:0] MIDI_PHYSICAL_BASE = 32'h30000000,\n    parameter [63:0] MIDI_PHYSICAL_BYTES_LIMIT = 64'd67108864"
    text = '// Generated by fpga/midi/generate_pipeline.py.\n`include "state_processor_defs.svh"\n'
    text += 'module midi_audio_pipeline_axi #(\n'+params+'\n) (\n'
    text += ',\n'.join('    '+p+n for p,n in public+axi)+'\n);\n'
    for prefix,n in private:
        text += '    '+re.sub(r'(input|output)\s+(wire|reg)', 'wire', prefix)+n+';\n'
    text += '    midi_audio_pipeline #(\n'+',\n'.join(f'        .{n}({n})' for n in names)+'\n    ) core (.*);\n'
    text += "    wire [63:0] checked_bytes = midi_memory_arena_bytes<=MIDI_PHYSICAL_BYTES_LIMIT ? midi_memory_arena_bytes : 0;\n"
    text += '    word_axi #(.DATA_WIDTH(MIDI_AXI_DATA_WIDTH),.REGISTER_REQUEST(1)) midi_memory (\n'
    fixed = dict(clk='clk',reset='reset',arena_base='midi_arena_base',arena_bytes='checked_bytes',physical_base='MIDI_PHYSICAL_BASE')
    mappings = []
    for _,n in word_ports:
        mappings.append(f'        .{n}({fixed.get(n,"midi_"+n)})')
    text += ',\n'.join(mappings)+'\n    );\nendmodule\n'
    return text

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    core = generate()
    for name, text in [('midi_audio_pipeline',core),('midi_audio_pipeline_axi',generate_axi(core))]:
        path = HERE/'rtl'/f'{name}.sv'
        if args.check:
            if path.read_text() != text: raise SystemExit(f'Stale generated {name}')
        else:
            path.write_text(text)
