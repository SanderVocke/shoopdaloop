#!/usr/bin/env python3
"""Join indexed MMIO to the actual semantic audio/media/recovery pipeline."""
import argparse
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
AXI = HERE.parent / "axi_memory"
sys.path.insert(0, str(AXI))
from generate_tops import header


def generate():
    core, ports = header((AXI / "rtl/fifo_recovery_pipeline_axi.sv").read_text())
    _, mmio = header((HERE / "rtl/fifo_mmio.sv").read_text())
    core_ports = {name: declaration for declaration, name in ports}
    connections = {"epoch": "runtime_epoch", "fault_sequence": "first_fault_sequence"}
    expressions = {"quantum_done": "done && !faulted && error_code==0",
                   "quantum_cycles": "(&diagnostic_cycles) ? diagnostic_cycles : diagnostic_cycles+32'd1"}
    external = {"irq", "audio_xruns"}
    local = {"abort_request"}
    private = {"pipeline_fault_cause"}
    for declaration, name in mmio:
        if name.startswith("s_axi_") or name in external or name in expressions or name in local:
            continue
        target = connections.get(name, name)
        assert target in core_ports, (name, target)
        if declaration.startswith("output"):
            assert core_ports[target].startswith("input"), name
            private.add(target)
        elif name not in {"clk", "reset"}:
            assert core_ports[target].startswith("output"), name
    assert all(core_ports[n].startswith("output") for n in ["done", "faulted", "error_code", "diagnostic_cycles"])
    public = [(p, n) for p, n in ports if n not in private]
    public += [(p.replace("output reg", "output wire"), n) for p, n in mmio if n.startswith("s_axi_") or n in external]
    public += [("input wire ", "audio_fault"), ("input wire ", "watchdog_fault")]
    params = core[2].strip().replace("PHYSICAL_BYTES_LIMIT = 64'h100000000", "PHYSICAL_BYTES_LIMIT = 64'h08000000")
    names = re.findall(r"parameter\s+(?:integer|\[[^\]]+\])\s+(\w+)\s*=", params)
    params += ",\n    parameter integer CORE_CLOCK_HZ = 100_000_000"
    result = '// Generated by generate_semantic_mmio.py; do not edit by hand.\n`include "state_processor_defs.svh"\n\n'
    result += "module fifo_mmio_pipeline_axi #(\n    " + params + "\n) (\n"
    result += ",\n".join("    " + p + n for p, n in public) + "\n);\n"
    for p, n in ports:
        if n in private:
            result += "    " + re.sub(r"(?:input|output)\s+(?:wire|reg)", "wire", p) + n + ";\n"
    for p, n in mmio:
        if n in local:
            result += "    " + re.sub(r"(?:input|output)\s+(?:wire|reg)", "wire", p) + n + ";\n"
    result += "    assign pipeline_fault_cause = (pipeline_fault ? 32'd64 : 0) | (audio_fault ? 32'd2 : 0)\n"
    result += "        | (watchdog_fault ? 32'd32 : 0) | (abort_request ? 32'd16 : 0);\n"
    settings = {"LOOPS": "LOOP_DEPTH", "SYSTEM_REGISTERS": "1", "EPOCH_RESET_COUPLED": "1", "CORE_CLOCK_HZ": "CORE_CLOCK_HZ",
                "ARENA_BASE": "PHYSICAL_BASE", "ARENA_BYTES": "PHYSICAL_BYTES_LIMIT",
                "PROGRAM_DEPTH": "PROGRAM_DEPTH", "STATE_DEPTH": "STATE_DEPTH",
                "JOB_DEPTH": "JOB_DEPTH > 512 ? 512 : JOB_DEPTH", "BUFFERS": "BUFFERS", "VIEWS": "VIEWS",
                "MEDIA_BLOCKS": "SLOTS/BLOCK_CHUNKS", "CHUNK_FRAMES": "CHUNK_FRAMES",
                "BLOCK_CHUNKS": "BLOCK_CHUNKS", "QUANTUM": "32"}
    result += "    fifo_mmio #(\n        " + ",\n        ".join(f".{n}({v})" for n, v in settings.items())
    result += ") mmio (.clk(clk), .reset(reset),\n"
    result += "        .runtime_reset(runtime_reset), .epoch(runtime_epoch),\n"
    result += "        .fault_sequence(first_fault_sequence),\n"
    result += ",\n".join(f"        .{n}({v})" for n, v in expressions.items()) + ", .*);\n"
    result += "    fifo_recovery_pipeline_axi #(\n        "
    result += ",\n        ".join(f".{n}({n})" for n in names)
    return result + ") pipeline (.pipeline_fault(pipeline_fault || audio_fault || watchdog_fault || abort_request), .*);\nendmodule\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = HERE / "rtl/fifo_mmio_pipeline_axi.sv"
    text = generate()
    if args.check:
        if not path.is_file() or path.read_text() != text:
            raise SystemExit(f"stale generated top: {path}; run {__file__}")
    else:
        path.write_text(text)


if __name__ == "__main__":
    main()
