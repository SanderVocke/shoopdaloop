#!/usr/bin/env python3
"""Write reproducible scenario estimates for the audio-chunk design note."""

import argparse
from dataclasses import asdict, replace
import json
from pathlib import Path

from model_audio_chunks import Assumptions, estimate


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--output", type=Path, default=Path("docs/design/chunks"))
    args = parser.parse_args()
    base = Assumptions()
    cases = {
        "one_capture_source": base,
        "sixteen_capture_sources": replace(base, sources=16),
        "128_passive_views": replace(base, retained_views=128),
        "transient_capture": replace(base, transient_capture=True),
        "routing_and_moderate_dsp": replace(base, sources=16, copy_edges=64, materializations=32, dsp_inputs=2),
        "dsp_dominated": replace(base, sources=16, copy_edges=64, materializations=512, dsp_inputs=2),
        "shared_signal_writers_and_deletion": replace(base, sources=16, retained_views=16, writers=8, extra_reclaim_nodes=32),
        "cold_counter_sensitivity": replace(base, reference_access_bytes=128),
    }
    data = {
        name: {"assumptions": asdict(assumptions),
               "estimates": [estimate(assumptions, b) for b in (2, 4, 8, 16, 32)]}
        for name, assumptions in cases.items()
    }
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "estimates.json").write_text(json.dumps(data, indent=2) + "\n")
    lines = [
        "# Audio-chunk scenario estimates",
        "",
        "Generated by `python3 scripts/report_audio_chunk_design.py`.",
        "All rates are decimal MB/s of modeled software traffic, not measured DRAM traffic or timing.",
        "The legacy comparator excludes its index work; the candidate includes its index and eventual path retirement.",
        "The cold-counter row is a sensitivity envelope, not a complete cache model.",
        "",
        "Four-way candidate, 48 kHz, Q=32, stereo, 256-frame callbacks:",
        "",
        "| Scenario | Legacy comparator MB/s | Candidate MB/s | Ratio | Reclaim units/callback | Sample reservation MiB | Index reservation MiB | Arena KiB |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, case in data.items():
        row = next(row for row in case["estimates"] if row["fanout"] == 4)
        lines.append(
            f"| {name} | {row['legacy_comparator_MB_per_second']:.3f} | "
            f"{row['candidate_MB_per_second']:.3f} | {row['logical_traffic_ratio']:.2f} | "
            f"{row['reclaim_units_per_callback']} | {row['sample_reservation_bytes'] / 2**20:.3f} | "
            f"{row['index_reservation_bytes'] / 2**20:.3f} | {row['arena_sample_bytes'] / 1024:.3f} |")
    lines += [
        "",
        "Reservations deliberately charge each retained view as if its whole interval could become independent.",
        "They include one callback of allocation staging, but exclude root tables, command staging, reclamation backlog headroom, processor state and MIDI.",
        "They are capacity illustrations, not a complete admission formula.",
        "",
        "Fanout sensitivity for one capture source:",
        "",
        "| Fanout | Height | Node bytes | Ordinary MB/s | Cold-counter MB/s |",
        "| ---: | ---: | ---: | ---: | ---: |",
    ]
    for normal, cold in zip(data["one_capture_source"]["estimates"], data["cold_counter_sensitivity"]["estimates"]):
        lines.append(f"| {normal['fanout']} | {normal['height']} | {normal['node_bytes']} | "
                     f"{normal['candidate_MB_per_second']:.3f} | {cold['candidate_MB_per_second']:.3f} |")
    (args.output / "estimates.md").write_text("\n".join(lines) + "\n")
    print(f"Wrote {args.output / 'estimates.json'} and {args.output / 'estimates.md'}")


if __name__ == "__main__":
    main()
